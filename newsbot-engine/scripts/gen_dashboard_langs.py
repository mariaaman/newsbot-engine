#!/usr/bin/env python3
"""Writes dashboard/src/langs.js from newsbot/langs.py (the one source of truth for the output languages).
tests/test_languages.py fails when the committed file is out of date: run this script and commit the result."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from newsbot.langs import LANGUAGES  # noqa: E402


def render() -> str:
    rows = [{"code": m["code"], "name": m["name"], "native": m["native"], "rtl": m["rtl"], "spaceless": m["spaceless"],
             "ui": m["ui"] is not None or m["code"] == "bn", "min_words": m["min_words"]} for m in LANGUAGES.values()]
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    return ("// GENERATED by scripts/gen_dashboard_langs.py from newsbot/langs.py. Do not edit.\n"
            "// ui: the site has translated UI labels for the language (false = English labels until someone translates them).\n"
            f"export const CATALOG = [\n{body},\n];\nexport const CODES = CATALOG.map((l) => l.code);\n")


if __name__ == "__main__":
    (ROOT / "dashboard" / "src" / "langs.js").write_text(render(), encoding="utf-8")
    print("dashboard/src/langs.js written")
